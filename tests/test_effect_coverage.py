"""Sanity tests for ``scripts/measure_effect_coverage.py``.

These guard against the script silently breaking as either the Rust
``Effect`` enum or the Python ``Effect`` vocab evolves. The most
load-bearing test is the orphan-empty regression guard
(``test_no_orphan_rust_variants``) — if a Rust variant is added without
either a 1:1 Python class name or an entry in ``RUST_TO_PYTHON_OVERRIDES``
or ``RUST_AHEAD_OF_POOL``, that test fails and forces a docs+coverage
audit on the same commit as the bridge change.

Skipped if the ``mtg_bot_engine`` PyO3 extension isn't built.
"""

from __future__ import annotations

import importlib.util
import re
import sys
from pathlib import Path

import pytest

pytest.importorskip("mtg_bot_engine")


REPO_ROOT = Path(__file__).resolve().parents[1]
SCRIPT_PATH = REPO_ROOT / "scripts" / "measure_effect_coverage.py"
DOC_PATH = REPO_ROOT / "docs" / "RUST_EFFECT_COVERAGE.md"


def _load_script():
    """Import the script module under a stable name without invoking
    its ``main()``. Returns the loaded module."""
    spec = importlib.util.spec_from_file_location(
        "_measure_effect_coverage_under_test", SCRIPT_PATH
    )
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


def test_script_runs_and_writes_doc():
    """The script's ``main()`` runs to completion and writes the
    target markdown file. Implicitly verifies that the Rust parse,
    Python parse, and markdown render all succeed end to end."""
    mod = _load_script()
    mod.main()
    assert DOC_PATH.exists(), f"expected {DOC_PATH} to exist after main()"
    text = DOC_PATH.read_text(encoding="utf-8")
    assert text.startswith(
        "Generated by `scripts/measure_effect_coverage.py`"
    ), "auto-generated header missing — script may have been short-circuited"
    assert "# Rust Effect bridge coverage vs Python vocab" in text


def test_headline_numbers_are_sensible():
    """The X-of-N and X'-of-N' numbers in the generated doc must be
    positive integers with percentages in [0, 100]. Catches a regex
    drift in the markdown template (or a divide-by-zero edge case if
    the Python vocab walk returns nothing)."""
    mod = _load_script()
    mod.main()
    text = DOC_PATH.read_text(encoding="utf-8")

    # Look for "X of N Python Effect classes covered (Y%)" and the
    # twin "X of N per-card emissions covered (Y%)" lines.
    class_line = re.search(
        r"\*\*(\d+) of (\d+) Python Effect classes covered \(([\d.]+)%\)\*\*",
        text,
    )
    assert class_line, "class-count headline line missing from generated doc"
    covered, total, pct = class_line.groups()
    covered_n, total_n, pct_f = int(covered), int(total), float(pct)
    assert covered_n >= 0
    assert total_n > 0
    assert covered_n <= total_n
    assert 0.0 <= pct_f <= 100.0

    emit_line = re.search(
        r"\*\*(\d+) of (\d+) per-card emissions covered \(([\d.]+)%\)\*\*",
        text,
    )
    assert emit_line, "emissions headline line missing from generated doc"
    em_cov, em_tot, em_pct = emit_line.groups()
    em_cov_n, em_tot_n, em_pct_f = int(em_cov), int(em_tot), float(em_pct)
    assert em_cov_n >= 0
    assert em_tot_n > 0
    assert em_cov_n <= em_tot_n
    assert 0.0 <= em_pct_f <= 100.0


def test_no_orphan_rust_variants():
    """Every Rust ``Effect`` variant must map to a Python class that
    appears in the parsed pool, OR be explicitly allowlisted in
    ``RUST_AHEAD_OF_POOL`` for the documented "bridge is ahead of the
    pool" case.

    This is the regression guard against bridge drift: if someone
    adds a Rust variant with a misspelled or stale Python counterpart,
    this test fails and forces a name-mapping fix on the same commit.
    """
    mod = _load_script()
    py_classes, _examples, _n = mod.collect_python_effect_vocab()
    rust_variants = mod.collect_rust_effect_variants()
    py_class_set = set(py_classes.keys())

    orphans: list[tuple[str, str]] = []
    for v in rust_variants:
        py_name = mod.map_rust_to_python(v)
        if py_name not in py_class_set and v not in mod.RUST_AHEAD_OF_POOL:
            orphans.append((v, py_name))

    assert orphans == [], (
        f"Rust variant(s) with no Python counterpart: {orphans}. "
        f"Either add a mapping to RUST_TO_PYTHON_OVERRIDES, allowlist "
        f"the variant in RUST_AHEAD_OF_POOL (bridge is ahead of pool), "
        f"or fix the variant name to match Python."
    )


def test_rust_variant_extraction_finds_known_variants():
    """Sanity-check the regex-based Rust variant extractor: it must
    find the long-standing ``DealDamage``, ``DrawCards``, and
    ``GainLife`` variants. If the regex breaks (e.g. the Rust file's
    formatting changes), this test surfaces the regression directly
    instead of letting it manifest as a confusing coverage drop."""
    mod = _load_script()
    rust_variants = mod.collect_rust_effect_variants()
    assert "DealDamage" in rust_variants
    assert "DrawCards" in rust_variants
    assert "GainLife" in rust_variants
    # The extractor must return CamelCase identifiers, not Rust
    # keywords or comment tokens.
    for v in rust_variants:
        assert v and v[0].isupper(), f"non-CamelCase variant slipped in: {v!r}"
