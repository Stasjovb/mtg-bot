"""``mtg_bot.cards.pool_coverage`` + ``scripts/measure_cube_coverage.py``."""

from __future__ import annotations

import importlib.util
import sys
from pathlib import Path

import pytest

from mtg_bot.cards import pool_coverage as pc

SCRIPT_PATH = Path(__file__).resolve().parents[1] / "scripts" / "measure_cube_coverage.py"


def _card(name, type_line, text="", *, layout="normal", keywords=(), mana_cost="", faces=None):
    card = {
        "name": name, "type_line": type_line, "oracle_text": text,
        "layout": layout, "keywords": list(keywords), "mana_cost": mana_cost,
    }
    if faces is not None:
        card["card_faces"] = faces
    return card


CARDS = [
    _card("Grizzly Bears", "Creature — Bear", "", mana_cost="{1}{G}"),
    _card("Storm Crow", "Creature — Bird", "Flying (This creature can't be blocked except by creatures with flying or reach.)", keywords=["Flying"], mana_cost="{1}{U}"),
    _card("Wind Drake", "Creature — Drake", "Flying", keywords=["Flying"], mana_cost="{2}{U}"),
    _card("Shock", "Instant", "Shock deals 2 damage to any target.", mana_cost="{R}"),
    _card("Bolt", "Instant", "Bolt deals 3 damage to any target.", mana_cost="{R}"),
    _card("Witch // Meadow", "Creature — Human // Land", layout="modal_dfc",
          faces=[{"oracle_text": "Flash"}, {"oracle_text": "{T}: Add {W}."}], keywords=["Flash"]),
    _card("Jace", "Legendary Planeswalker — Jace", "+1: Draw a card.", mana_cost="{2}{U}{U}"),
]


def test_primary_type_uses_front_face():
    assert pc.primary_type(CARDS[0]) == "Creature"
    assert pc.primary_type(CARDS[5]) == "Creature"
    assert pc.primary_type(CARDS[6]) == "Planeswalker"
    assert pc.primary_type({"type_line": "Tribal Instant"}) == "Instant"
    assert pc.primary_type({"type_line": "Conspiracy"}) == "Other"


def test_oracle_lines_strip_reminder_and_walk_faces():
    assert pc.oracle_lines(CARDS[1]) == ["Flying"]
    assert pc.oracle_lines(CARDS[5]) == ["Flash", "{T}: Add {W}."]
    assert pc.oracle_lines(CARDS[0]) == []


def test_line_shape_normalizes():
    assert pc.line_shape("Shock deals 2 damage to any target.", "Shock") == \
        "CARDNAME deals N damage to any target."
    assert pc.line_shape("{T}: Add {W}.", "Witch // Meadow") == "{M}: Add {M}."
    assert pc.line_shape("Jace, Vryn's Prodigy gets +1/+1", "Jace, Vryn's Prodigy // Jace, Telepath") == \
        "CARDNAME gets +N/+N"


def test_summarize_coverage_buckets():
    s = pc.summarize_coverage(CARDS, ["Grizzly Bears", "Shock", "Nonexistent"], pool_name="t")
    assert (s.total, s.claimed) == (7, 2)
    assert s.pct == pytest.approx(200 / 7)
    assert s.by_type["Creature"] == (1, 4)
    assert s.by_type["Instant"] == (1, 2)
    assert s.by_type["Planeswalker"] == (0, 1)
    assert s.by_layout["modal_dfc"] == (0, 1)
    assert s.unclaimed_keywords[0] == ("Flying", 2)
    # The two flying creatures share a shape; the shape table only lists shapes seen >= 2.
    shapes = {shape: (n, ex) for shape, n, ex in s.unclaimed_shapes}
    assert shapes["Flying"] == (2, "Storm Crow")
    assert "CARDNAME deals N damage to any target." not in shapes  # Bolt alone (Shock claimed)
    # Sorted by primary type, then name: Creature < Instant < Planeswalker.
    assert [c["name"] for c in s.unclaimed_cards] == [
        "Storm Crow", "Wind Drake", "Witch // Meadow", "Bolt", "Jace",
    ]
    assert s.claimed_names == ["Grizzly Bears", "Shock"]  # names outside the pool dropped


def test_summarize_coverage_empty():
    s = pc.summarize_coverage([], [])
    assert s.pct == 0.0 and s.total == 0


def test_render_markdown_sections():
    s = pc.summarize_coverage(CARDS, ["Grizzly Bears"], pool_name="t")
    md = pc.render_markdown(s, script_name="x.py")
    assert md.startswith("Generated by `x.py`")
    for heading in ("## By primary type", "## By layout", "## Keywords on unclaimed cards",
                    "## Most common oracle-line shapes", "## Unclaimed cards", "### Creature",
                    "## Claimed cards"):
        assert heading in md
    assert "**1 of 7 cards claimed (14.3%).**" in md
    assert "(no rules text)" not in md  # Bears is claimed; every unclaimed card has text
    assert "| Flying | 2 |" in md


def test_render_markdown_escapes_pipes_and_no_text():
    cards = [_card("Vanilla", "Creature — Ox"), _card("Piped", "Instant", "A | B")]
    md = pc.render_markdown(pc.summarize_coverage(cards, []))
    assert "(no rules text)" in md
    assert "A \\| B" in md


@pytest.fixture(scope="module")
def script():
    spec = importlib.util.spec_from_file_location("_measure_cube_coverage_under_test", SCRIPT_PATH)
    assert spec is not None and spec.loader is not None
    mod = importlib.util.module_from_spec(spec)
    sys.modules[spec.name] = mod
    spec.loader.exec_module(mod)
    return mod


def test_script_writes_doc(script, tmp_path, capsys):
    out = tmp_path / "cov.md"
    assert script.main(["--pool", "cube", "--out", str(out)]) == 0
    text = out.read_text(encoding="utf-8")
    assert text.startswith("Generated by `scripts/measure_cube_coverage.py`")
    assert "# Parser coverage of the `cube` card pool" in text
    assert "cube:" in capsys.readouterr().out


def test_script_no_write(script, tmp_path):
    out = tmp_path / "cov.md"
    assert script.main(["--pool", "cube", "--out", str(out), "--no-write"]) == 0
    assert not out.exists()


def test_committed_doc_is_fresh(script):
    """``docs/CUBE_POOL_COVERAGE.md`` must match the parser's current
    claims — regenerate it when grammar lands."""
    from mtg_bot.cards.parser_source import OracleParserCardSource
    from mtg_bot.cards.pools import load_pool_cards

    doc = script.DEFAULT_OUT.read_text(encoding="utf-8")
    summary = pc.summarize_coverage(
        load_pool_cards("cube"), OracleParserCardSource(pool="cube").claimed_names, pool_name="cube",
    )
    assert pc.render_markdown(summary) == doc
